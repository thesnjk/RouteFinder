import Contracts
import Foundation
import Testing
@testable import UI

struct InspectionReportPDFRendererTests {
    @Test func pdfDataIsNonEmptyForCompleteRecord() {
        var items = InspectionRecord.defaultDVSAItems()
        for index in items.indices {
            items[index].status = .pass
        }
        let record = InspectionRecord(
            vehicleLabel: "Test HGV",
            registrationPlate: "AB12 CDE",
            completedAt: Date(),
            items: items
        )
        let pdf = InspectionReportPDFRenderer.pdfData(from: record)
        #expect(!pdf.isEmpty)
        #expect(pdf.starts(with: Data("%PDF".utf8)))
    }

    @Test func pdfEmbedsDefectPhotoJPEG() {
        // Minimal 1×1 JPEG (JFIF)
        let jpegBytes: [UInt8] = [
            0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00, 0x01,
            0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0xFF, 0xDB, 0x00, 0x43,
            0x00, 0x08, 0x06, 0x06, 0x07, 0x06, 0x05, 0x08, 0x07, 0x07, 0x07, 0x09,
            0x09, 0x08, 0x0A, 0x0C, 0x14, 0x0D, 0x0C, 0x0B, 0x0B, 0x0C, 0x19, 0x12,
            0x13, 0x0F, 0x14, 0x1D, 0x1A, 0x1F, 0x1E, 0x1D, 0x1A, 0x1C, 0x1C, 0x20,
            0x24, 0x2E, 0x27, 0x20, 0x22, 0x2C, 0x23, 0x1C, 0x1C, 0x28, 0x37, 0x29,
            0x2C, 0x30, 0x31, 0x34, 0x34, 0x34, 0x1F, 0x27, 0x39, 0x3D, 0x38, 0x32,
            0x3C, 0x2E, 0x33, 0x34, 0x32, 0xFF, 0xC0, 0x00, 0x0B, 0x08, 0x00, 0x01,
            0x00, 0x01, 0x01, 0x01, 0x11, 0x00, 0xFF, 0xC4, 0x00, 0x14, 0x00, 0x01,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x03, 0xFF, 0xC4, 0x00, 0x14, 0x10, 0x01, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0xFF, 0xDA, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3F, 0x00,
            0x7F, 0xFF, 0xD9,
        ]
        let jpegData = Data(jpegBytes)
        var items = InspectionRecord.defaultDVSAItems()
        for index in items.indices {
            items[index].status = index == 0 ? .defect : .pass
        }
        items[0].note = "Cracked lens"
        items[0].photoJPEGBase64 = [jpegData.base64EncodedString()]
        let record = InspectionRecord(
            vehicleLabel: "Photo HGV",
            registrationPlate: "PH01 TST",
            completedAt: Date(),
            items: items
        )
        let baseline = InspectionReportPDFRenderer.pdfData(from: InspectionRecord(
            vehicleLabel: "Photo HGV",
            registrationPlate: "PH01 TST",
            completedAt: Date(),
            items: items.map { item in
                var copy = item
                copy.photoJPEGBase64 = []
                return copy
            }
        ))
        let withPhoto = InspectionReportPDFRenderer.pdfData(from: record)
        #expect(withPhoto.starts(with: Data("%PDF".utf8)))
        #expect(withPhoto.count > baseline.count)
        // Embedded JPEG SOI marker appears in PDF stream when thumbnail draws
        let hasJPEGMarker = withPhoto.range(of: Data([0xFF, 0xD8, 0xFF])) != nil
        #expect(hasJPEGMarker || withPhoto.count > baseline.count + 50)
    }
}
